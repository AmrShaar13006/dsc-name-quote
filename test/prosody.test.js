// مدقق العروض: أبيات مشهورة مشكولة يجب أن تستقيم على بحورها، والبيت المكسور يُرفض
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { syllables, metersOf } from '../src/prosody.js';

const KNOWN = [
  ['الطويل', 'قِفَا نَبْكِ مِنْ ذِكْرَى حَبِيبٍ وَمَنْزِلِ', 'بِسِقْطِ اللِّوَى بَيْنَ الدَّخُولِ فَحَوْمَلِ'],
  ['الطويل', 'سَتُبْدِي لَكَ الْأَيَّامُ مَا كُنْتَ جَاهِلًا', 'وَيَأْتِيكَ بِالْأَخْبَارِ مَنْ لَمْ تُزَوِّدِ'],
  ['البسيط', 'الْخَيْلُ وَاللَّيْلُ وَالْبَيْدَاءُ تَعْرِفُنِي', 'وَالسَّيْفُ وَالرُّمْحُ وَالْقِرْطَاسُ وَالْقَلَمُ'],
  ['البسيط', 'أَنَا الَّذِي نَظَرَ الْأَعْمَى إِلَى أَدَبِي', 'وَأَسْمَعَتْ كَلِمَاتِي مَنْ بِهِ صَمَمُ'],
  ['الكامل', 'يَا أَيُّهَا الرَّجُلُ الْمُعَلِّمُ غَيْرَهُ', 'هَلَّا لِنَفْسِكَ كَانَ ذَا التَّعْلِيمُ'],
  ['الوافر', 'إِذَا غَامَرْتَ فِي شَرَفٍ مَرُومٍ', 'فَلَا تَقْنَعْ بِمَا دُونَ النُّجُومِ'],
  ['الخفيف', 'كُلُّ حَيٍّ وَإِنْ تَطَاوَلَ عُمْرًا', 'آيِبٌ مَرَّةً إِلَى الرَّحْمٰنِ'],
  ['المتقارب', 'إِذَا الْمَرْءُ لَمْ يَرْعَ عَهْدَ الصَّدِيقِ', 'فَلَيْسَ لَهُ فِي الْوَفَاءِ نَصِيبُ'],
  // مفاتيح البحور (صفي الدين الحلي): الشطر الثاني تفاعيل البحر نفسها
  ['السريع', 'بَحْرٌ سَرِيعٌ مَا لَهُ سَاحِلُ', 'مُسْتَفْعِلُنْ مُسْتَفْعِلُنْ فَاعِلُنْ'],
  ['الرجز', 'فِي أَبْحُرِ الْأَرْجَازِ بَحْرٌ يَسْهُلُ', 'مُسْتَفْعِلُنْ مُسْتَفْعِلُنْ مُسْتَفْعِلُ'],
  ['الرمل', 'رَمَلُ الْأَبْحُرِ تَرْوِيهِ الثِّقَاتُ', 'فَاعِلَاتُنْ فَاعِلَاتُنْ فَاعِلَاتُ'],
  ['الطويل', 'طَوِيلٌ لَهُ دُونَ الْبُحُورِ فَضَائِلُ', 'فَعُولُنْ مَفَاعِيلُنْ فَعُولُنْ مَفَاعِلُ'],
];

test('العروض: أبيات معروفة تستقيم على بحورها', () => {
  for (const [meter, a, b] of KNOWN) {
    const found = metersOf(a, b);
    assert.ok(found.includes(meter), `${a} / ${b}\n  ${syllables(a)} | ${syllables(b)} → ${found.join('، ') || 'لا بحر'}`);
  }
});

test('العروض: البيت المكسور لا يستقيم، والحرف غير المشكول يُرفض', () => {
  // حذف كلمة من شطر طويل
  assert.deepEqual(metersOf('قِفَا نَبْكِ مِنْ ذِكْرَى حَبِيبٍ', 'بِسِقْطِ اللِّوَى بَيْنَ الدَّخُولِ فَحَوْمَلِ'), []);
  // تبديل كلمة يكسر الوزن
  assert.deepEqual(metersOf('إِذَا غَامَرْتَ فِي شَرَفٍ عَظِيمٍ كَبِيرٍ', 'فَلَا تَقْنَعْ بِمَا دُونَ النُّجُومِ'), []);
  assert.throws(() => syllables('قفا نبك من ذكرى'), /بلا حركة/);
});

test('العروض: همزة الوصل وأل الشمسية والقمرية وحروف المد', () => {
  assert.equal(syllables('وَالْحِرْصُ'), '---');                // وَلْ حِرْ صُو
  assert.equal(syllables('وَالِدٌ'), '-u-');                      // وَا لِ دُنْ
  assert.equal(syllables('فِي الدُّنْيَا'), '---');               // فِدْ دُنْ يَا
  assert.equal(syllables('مَنْ بِهِ صَمَمُ'), '-u-uu-');          // مَنْ بِ هِي صَ مَ مُو
  assert.equal(syllables('بِهِ الْعِلْمُ'), 'u---');              // بِ هِلْ عِلْ مُو: الصلة تسقط قبل الساكن
});
