import { test } from 'node:test';
import assert from 'node:assert/strict';
import { splitVerse, countLetters } from '../src/verse.js';

// عيّنات حقيقية كما أعادها الديوان (الشطران ملتصقان)
const REAL = [
  {
    title: 'إن كنت ما تدري، فتلك مصيبة',
    text: 'إن كنتَ ما تدري، فتلكَ مصيبةً،أو كنتَ تَدري، فالمُصيبَةُ أعظَمُ',
    first: 'إن كنتَ ما تدري، فتلكَ مصيبةً،',
    second: 'أو كنتَ تَدري، فالمُصيبَةُ أعظَمُ',
    single: true,
  },
  {
    title: 'فما ضاق باب الله عن قصد سائل',
    text: 'فما ضاق باب الله عن قصد سائلٍولا سد من دون الإجابة حجبه',
    first: 'فما ضاق باب الله عن قصد سائلٍ',
    second: 'ولا سد من دون الإجابة حجبه',
    single: true,
  },
  {
    title: 'وما الحب إلا أن تكون وأن ترى',
    text: 'وَمَا الحُبُّ إلا أَنْ تَكونَ وأَنْ تُرَىوتَدخُلَ في سُكْرِ الشِعورِ المُخَامرِ',
    first: 'وَمَا الحُبُّ إلا أَنْ تَكونَ وأَنْ تُرَى',
    second: 'وتَدخُلَ في سُكْرِ الشِعورِ المُخَامرِ',
    single: true,
  },
  {
    // العنوان فيه «تفارقة» والنص «تُفارِقُهُ»، والنص بيتان
    title: 'سافر تجد عوضاً عمن تفارقة',
    text: 'سافِر تَجِد عِوَضاً عَمَّن تُفارِقُهُوَاِنصَب فَإِنَّ لَذيذَ العَيشِ في النَصَبِإِنّي رَأَيتُ وُقوفَ الماءِ يُفسِدُهُإِن ساحَ طابَ وَإِن لَم يَجرِ لَم يَطِبِ',
    first: 'سافِر تَجِد عِوَضاً عَمَّن تُفارِقُهُ',
    single: false,
  },
  {
    title: 'هل عشت حقاً ؟ يكاد الشك يغلبني',
    text: 'هَلْ عِشْتُ حَقّاً؟ يَكَادُ الشَّكُّ يَغْلِبُنِيأَمْ كَانَ مَا عِشْتُهُ أَضْغَاثَ أَحْلَامِ',
    first: 'هَلْ عِشْتُ حَقّاً؟ يَكَادُ الشَّكُّ يَغْلِبُنِي',
    second: 'أَمْ كَانَ مَا عِشْتُهُ أَضْغَاثَ أَحْلَامِ',
    single: true,
  },
];

test('تقسيم الأبيات الحقيقية من الديوان إلى شطرين', () => {
  for (const s of REAL) {
    const r = splitVerse(s.title, s.text);
    assert.ok(r, s.title);
    assert.equal(r.first, s.first, s.title);
    if (s.second) assert.equal(r.second, s.second, s.title);
    assert.equal(r.singleVerse, s.single, `${s.title}: بيت واحد؟`);
  }
});

test('رفض العنوان الذي لا يطابق بداية النص', () => {
  assert.equal(splitVerse('عنوان مختلف تمامًا عن النص', 'وما الحب إلا أن تكون وأن ترى وتدخل في سكر الشعور'), null);
  assert.equal(splitVerse('', 'نص'), null);
  assert.equal(splitVerse('عنوان', ''), null);
});

test('عدّ الحروف يتجاهل التشكيل والتطويل والترقيم', () => {
  assert.equal(countLetters('مُحَمَّـــد، !'), 4);
  assert.equal(countLetters('ٱلله'), 4);
});
